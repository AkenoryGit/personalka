package com.akenory.personalka.data.db.entity

import androidx.room3.Entity

// ТЗ 3.8, 7.2. Только для телефона: на сервер, в копию и на другие устройства не попадает.

/**
 * Очередь изменений (Outbox): запись [rowId] таблицы [entity] изменилась и ещё не отправлена на сервер. Пишут её
 * триггеры SQLite в той же транзакции, что само изменение (`SyncOutbox`), поэтому ни одна правка не пройдёт мимо.
 * Повторные правки одной записи склеиваются: строка одна, [updatedAt] — последней правки; у стёртой совсем
 * («Удалить клиента полностью», 3.1) — на миллисекунду позже её последней правки: удаление не старше самой записи.
 * Отправляется запись целиком такой, какая она в таблице в момент отправки; записи нет — серверу уходит удаление
 * с пустыми данными.
 */
@Entity(tableName = "sync_outbox", primaryKeys = ["entity", "rowId"])
data class SyncOutboxEntity(
    val entity: String,
    val rowId: String,
    val updatedAt: Long,
)
