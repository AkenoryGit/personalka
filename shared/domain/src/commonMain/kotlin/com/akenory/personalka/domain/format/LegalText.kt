                ),
                LegalSection(
                    "Фото и видео — по желанию",
                    para(
                        "Только если отметите вторую галочку: тренер хранит фото и видео ребёнка с тренировок и соревнований в своём облачном " +
                            "хранилище, а в кабинете появится ссылка на них. Без галочки фото и видео не хранятся. Отозвать это согласие отдельно — написать тренеру.",
                    ),
