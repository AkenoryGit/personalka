                    ),
                ),
                LegalSection("Ваши данные", para("Фамилия и имя, телефон для связи с тренером.")),
                NOTHING_ELSE,
                PURPOSE,
                ACTIONS,
                WHERE,
                LegalSection(
                    "Подтверждение согласия",
                    para("Когда вы нажмёте «Продолжить», сервер запомнит время, ваши фамилию и имя, IP-адрес и браузер — это заменяет подпись на бумаге."),
                ),
                LegalSection(
