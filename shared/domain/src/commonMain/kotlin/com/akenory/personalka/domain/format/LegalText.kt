            )
        } else {
            listOf(
                LegalSection(
                    "Для кого эти данные",
                    para(
                        "Тренер ведёт их сам и открывает только вам. Видите их только вы и тренер. " +
                            "Другим людям — клубу, другим ученикам, рекламе и посторонним сервисам — тренер их не показывает и не передаёт.",
                    ),
                ),
                LegalSection("Кто", para(who)),
                LegalSection(
                    "Какие данные",
                    bullets(
                        "фамилия, имя, отчество, дата рождения и пол;",
                        "телефон для связи с тренером;",
                        "расписание, посещения и отмены с причиной («не сможет», «отъезд»);",
                        "записи тренера о тренировках: план, что сделали, как прошло;",
                        "результаты заплывов;",
                        "рабочие заметки тренера — в кабинете их нет;",
                        "если у тренера занимаются ваши родственники — отметка, кто кому родственник.",
