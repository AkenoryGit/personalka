package com.akenory.personalka.domain.format

import kotlinx.datetime.LocalDate

/** Кусок документа: абзац, список или таблица «цель — данные». */
sealed interface LegalBlock {
    data class Para(val text: String) : LegalBlock

    data class Bullets(val items: List<String>) : LegalBlock

    data class Table(val head: Pair<String, String>, val rows: List<Pair<String, String>>) : LegalBlock
}

/** Раздел документа: заголовок и его куски. */
data class LegalSection(val title: String, val blocks: List<LegalBlock>)

/** Документ: «Согласие на обработку персональных данных», «Редакция 1 от 24.10.2026», разделы. */
data class LegalDoc(val title: String, val edition: String, val sections: List<LegalSection>)

/**
 * Тексты согласия и политики обработки (ТЗ 6.1, 10.3) — редакция из `docs/legal` (шаг 2.6), согласованная Дмитрием.
 * Оператор — сам тренер: его полное ФИО и контакт для обращений подставляются из профиля (3.2). Бумажного согласия
 * нет (решение Дмитрия 24.10.2026) — только галочка в кабинете.
