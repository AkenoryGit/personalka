    private val WHERE = LegalSection(
        "Где хранятся",
        para(
            "В телефоне тренера и на его сервере в России. Резервные копии зашифрованы и тоже хранятся в России. " +
                "Кабинет открывается только по вашей личной ссылке, данных других учеников в нём нет.",
        ),
    )

    private fun para(text: String): List<LegalBlock> = listOf(LegalBlock.Para(text))

    private fun bullets(vararg items: String): List<LegalBlock> = listOf(LegalBlock.Bullets(items.toList()))
}
