    private val NOTHING_ELSE = LegalSection(
        "Чего нет",
        para("Сведений о здоровье — диагнозов, травм, болезней. Тренер их не записывает."),
    )

    private val PURPOSE = LegalSection(
        "Зачем",
        bullets(
            "вести учёт тренировок и сверять его с отчётом клуба о проведённых тренировках — сам тренер клубу данные не передаёт;",
            "связываться с вами по тренировкам;",
            "показывать вам в этом кабинете расписание, записи тренера и результаты.",
        ),
    )

    private val ACTIONS = LegalSection(
        "Что тренер делает с данными",
        para("Записывает, хранит, исправляет, использует для целей выше и удаляет — в приложении на телефоне и на сервере."),
