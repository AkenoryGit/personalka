object LegalText {
    /** Номер действующей редакции — пишется в согласие (`text_version`, 3.7). */
    const val VERSION = 1

    /**
     * С какой редакции согласие не спрашивается снова: правка слов — новая редакция без нового согласия, новые цели
     * или данные — этот номер поднимается до новой редакции (docs/legal, «Версии»).
     */
    const val ASK_AGAIN_FROM = 1

    /** Дата редакции 1 — день запуска кабинетов. */
    val EDITION_DATE = LocalDate(2026, 10, 24)

    const val CONSENT_TITLE = "Согласие на обработку персональных данных"
    const val POLICY_TITLE = "Политика обработки персональных данных"

    /** Нет контакта в профиле (кабинеты без него не включаются, 5.16) — всё равно есть куда обратиться. */
    const val NO_CONTACT = "сообщением тренеру напрямую"

    /** «Редакция 1 от 24.10.2026». */
    fun edition(version: Int = VERSION, date: LocalDate = EDITION_DATE): String = "Редакция $version от ${DateFormat.full(date)}"

