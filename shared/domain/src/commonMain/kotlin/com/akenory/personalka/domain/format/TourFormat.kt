package com.akenory.personalka.domain.format

import com.akenory.personalka.domain.tour.TourStop

/**
 * Тексты знакомства с приложением (ТЗ 5.18, шаги 5.3б и 5.3г, макет `docs/mockups/tour`). Пишутся для тренера,
 * который открыл приложение впервые: только о том, что у него уже включено — без дневника, кабинетов и облака,
 * пока он их сам не включил.
 */
object TourFormat {
    fun step(stop: TourStop): String = "Знакомство · ${stop.number} из ${TourStop.COUNT}"

    const val NEXT = "Дальше"
    const val SETUP = "Настроить"
    const val PICK_FOLDER = "Выбрать папку"
    const val FINISH = "Готово"

    const val CALENDAR_TITLE = "Добавьте тренировку"
    const val CALENDAR_TEXT = "Удерживайте пустое место в календаре — откроется новая тренировка. Внесите настоящую, " +
        "например завтрашнюю. Клиента можно завести прямо в форме: впишите фамилию и имя."
    const val CALENDAR_GESTURE = "Удерживайте выделенное место или нажмите «+»"

    const val CARD_TITLE = "Карточка тренировки"

    /** [autoDone] — «Проведено» ставится само (настройка тренера, по умолчанию включена). */
    fun cardDone(autoDone: Boolean): String =
        if (autoDone) "Проведённой тренировка отметится сама, когда закончится, — нажимать ничего не нужно."
        else "Когда тренировка пройдёт, нажмите «Проведено»."

    /** Правило списания (4.2): [minutes] — из настройки тренера («Ещё → Календарь»), «1 час», «1 час 30 минут». */
    fun cardCancel(minutes: Int): String =
        "Клиент отменил — нажмите «Отменить». Предупредил хотя бы за ${DurationFormat.long(minutes.toLong())} — " +
            "отмена без списания, позже — со списанием. Это время вы задаёте сами: «Ещё → Календарь»."

    const val CLIENTS_TITLE = "Клиенты"
    const val CLIENTS_TEXT = "Клиент из тренировки уже в списке. Нажмите на него, чтобы открыть карточку."
    const val CLIENTS_GESTURE = "Нажмите на клиента"
    const val CLIENTS_OPEN_TEXT = "В карточке клиента — его тренировки, постоянное расписание и результаты."
    const val CLIENTS_EMPTY_TITLE = "Добавьте клиента"
    const val CLIENTS_EMPTY_TEXT = "Фамилия и имя — остальное по желанию. Карточка клиента появится в этом списке."
    const val CLIENTS_EMPTY_GESTURE = "Нажмите «Добавить клиента»"

    const val HOME_TITLE = "Главная — с неё начинается день"

    /** Что попадает в «Нужно сделать»; дневник — только если тренер его включил. */
    fun homeText(diary: Boolean): String {
        val what = if (diary) "дневник, кого записать, кто ждёт свободное время" else "кого записать, кто ждёт свободное время"
        return "«Нужно сделать» — дела, которые ждут вас: $what. Нажмите на пункт — там пояснение и список. " +
            "«Деньги» — заработок за месяц."
    }

    const val SALARY_TITLE = "Настройте зарплату"
    const val SALARY_TEXT = "День зарплаты и ставки за каждый тип тренировки. Можно взять ставки-пример и поправить " +
        "по расчётному листку — около минуты. Или позже, в «Зарплате»."

    const val BACKUP_TITLE = "Сохраните данные"
    const val BACKUP_TEXT = "Всё хранится только в этом телефоне. Выберите папку — копия будет ложиться в неё сама " +
        "каждый день. Есть аккаунт — включите и копию на сервере: «Ещё → Аккаунт»."

    /** Папка уже выбрана: знакомство только говорит, что копия делается. */
    fun backupDone(folder: String): String = "Копия уже ложится сама в папку «$folder». Резервная копия и пароль к ней — здесь, в «Ещё»."

    const val NO_BACKUP_TITLE = "Без копии?"
    const val NO_BACKUP_TEXT = "Если телефон потеряется или сломается, клиенты, расписание и история тренировок пропадут насовсем."
    const val NO_BACKUP_NOTE = "Выбрать папку можно потом — пункт останется в «Нужно сделать»."
    const val NO_BACKUP = "Без копии"

    const val DONE = "Знакомство закончено. Повторить — «Ещё → Знакомство с приложением»."

    const val HELP = "Помощь"
    const val MORE_ITEM = "Знакомство с приложением"
    const val MORE_NOTE = "Шесть шагов, около двух минут"
}
